test('shows exact values and changes on hover, and dismisses them when leaving or filtering', async () => {
  const user = userEvent.setup()
  render(<SelectedWork />)
  await user.click(screen.getByText('Try a sample report', { selector: 'summary' }))
  const chart = await screen.findByRole('figure', { name: 'Completed reports by month' })
  const period = screen.getByRole('combobox', { name: 'Reporting period' })
  await user.selectOptions(period, 'secondQuarter')
  const bar = within(chart).getByRole('button', { name: 'Quality, April 2026, Completed reports 102' })
  const tip = () => chart.querySelector('[data-open="true"]')
  expect(bar).toHaveAccessibleDescription('Compared with March 2026. +9 (+9.7%)')

  await user.hover(bar)
  expect(tip()).toHaveTextContent('April 2026')
  expect(tip()).toHaveTextContent('102')
  expect(tip()).toHaveTextContent('+9 (+9.7%)')
  await user.hover(within(chart).getByText('Completed reports by month'))
  await waitFor(() => expect(tip()).toBeNull())
  await user.hover(bar)
  await user.unhover(bar)
  expect(tip()).toBeNull()

  const operations = within(chart).getByRole('button', { name: 'Operations, April 2026, Completed reports 24' })
  await user.hover(operations)
  expect(tip()).toHaveTextContent('Compared with March 2026')
  expect(tip()).toHaveTextContent('No previous value')
  await user.selectOptions(period, 'firstHalf')
  await user.selectOptions(period, 'secondQuarter')
  expect(tip()).toBeNull()
})

test('opens the point on keyboard focus, supports activation and Escape, and keeps descriptions available', async () => {
  const user = userEvent.setup()
  render(<SelectedWork />)
  const disclosure = screen.getByText('Try a sample report', { selector: 'summary' })
  await user.click(disclosure)
  const chart = await screen.findByRole('figure', { name: 'Completed reports by month' })
  const january = within(chart).getByRole('button', { name: 'Quality, January 2026, Completed reports 72' })
  expect(january).toHaveAccessibleDescription('Compared with December 2025. No previous value')

  screen.getByRole('button', { name: 'Reset filters' }).focus()
  await user.tab()
  expect(january).toHaveFocus()
  expect(chart.querySelector('[data-open="true"]')).toHaveTextContent('January 2026')
  await user.keyboard('{Escape}')
  expect(chart.querySelector('[data-open="true"]')).toBeNull()
  expect(january).toHaveFocus()
  await user.keyboard('{Enter}')
  expect(chart.querySelector('[data-open="true"]')).toHaveTextContent('Quality')
  const adjacent = within(chart).getByRole('button', { name: 'Utilization, January 2026, Completed reports 48' })
  await user.hover(adjacent)
  expect(chart.querySelector('[data-open="true"]')).toHaveTextContent('Utilization')
  await user.unhover(adjacent)
  expect(january).toHaveFocus()
  expect(chart.querySelector('[data-open="true"]')).toHaveTextContent('Quality')

  await user.click(disclosure)
  await user.click(disclosure)
  expect(chart.querySelector('[data-open="true"]')).toBeNull()
})
