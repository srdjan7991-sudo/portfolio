import { expect, test } from '@playwright/test'

test('follows TypeScript to the project evidence and returns focus through browser history', async ({ page }) => {
  await page.setViewportSize({ width: 768, height: 900 })
  await page.goto('./#skill-typescript')
  const projectLink = page.getByRole('link', { name: 'View work on Mede Analytics', exact: true })
  await expect(projectLink).toBeVisible()
  await projectLink.press('Enter')
  await expect(page).toHaveURL(/#work-mede$/)
  const project = page.getByRole('article', { name: 'Mede Analytics' })
  await expect(project).toBeFocused()
  await expect(project.getByText('What I built', { exact: true })).toBeVisible()
  await project.getByText('Read the case study', { exact: true }).press('Enter')
  await expect(project.getByText('Technical approach', { exact: true })).toBeVisible()
  await expect(project.getByText('User value', { exact: true })).toBeVisible()
  await page.goBack()
  await expect(projectLink).toBeFocused()
})

test('keeps Serbian concept demonstrations and code readable at 320 px', async ({ page }) => {
  await page.setViewportSize({ width: 320, height: 740 })
  await page.goto('./#expertise')
  await page.getByRole('switch', { name: 'Dark theme' }).click()
  await page.getByRole('switch', { name: 'EN / SR, Serbian language' }).click()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
  await expect(page.locator('html')).toHaveAttribute('lang', 'sr')
  await page.getByRole('button', { name: /Arhitektura aplikacija/ }).click()
  const separation = page.getByRole('tab', { name: 'Podela odgovornosti' })
  await separation.press('End')
  const panel = page.getByRole('tabpanel', { name: 'Modernizacija aplikacija' })
  await expect(panel.getByRole('button', { name: 'Jedan modul' })).toHaveAttribute('aria-pressed', 'true')
  const code = panel.locator('pre')
  await expect(code).toContainText('loadReports()')
  expect(await code.evaluate(node => node.scrollWidth)).toBe(await code.evaluate(node => node.clientWidth))
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(320)
})
